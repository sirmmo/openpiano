#!/usr/bin/env python3
"""Download a sparse set of acoustic grand piano samples (FluidR3 GM, CC BY 3.0)
and pack them into sounds/piano.js as base64 data URLs.

Samples are taken every 3 semitones (C, Eb, Gb, A); the app pitch-shifts the
nearest one for the notes in between. Packing them in a .js file means the app
also works offline and when index.html is opened straight from disk.

Usage: python3 tools/build-piano-samples.py
"""
import base64, json, os, urllib.request

BASE = "https://gleitz.github.io/midi-js-soundfonts/FluidR3_GM/acoustic_grand_piano-mp3/"
NAMES = ["A0"] + [f"{n}{o}" for o in range(1, 8) for n in ("C", "Eb", "Gb", "A")] + ["C8"]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "sounds", "piano.js")

samples = {}
for name in NAMES:
    with urllib.request.urlopen(BASE + name + ".mp3") as r:
        samples[name] = "data:audio/mpeg;base64," + base64.b64encode(r.read()).decode()
    print("got", name)

with open(OUT, "w") as f:
    f.write("/* Acoustic grand piano samples from the FluidR3 GM soundfont by Frank Wen,\n")
    f.write(" * via https://github.com/gleitz/midi-js-soundfonts\n")
    f.write(" * License: Creative Commons Attribution 3.0 (https://creativecommons.org/licenses/by/3.0/)\n")
    f.write(" * Generated by tools/build-piano-samples.py - do not edit. */\n")
    f.write("window.OP_PIANO_SAMPLES = " + json.dumps(samples, separators=(",", ":")) + ";\n")
print("wrote", OUT)
